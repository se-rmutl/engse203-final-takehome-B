-- เปิดการตรวจ foreign key (SQLite ปิดไว้เป็นค่าเริ่มต้น)
PRAGMA foreign_keys = ON;

-- ลบตารางลูกก่อนตารางแม่ เพราะ announcements อ้างถึง categories
DROP TABLE IF EXISTS announcements;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS users;

-- ───────────────────────────────────────────
-- users — บัญชีเจ้าหน้าที่ (ผู้อ่านข่าวทั่วไปไม่ต้องมีบัญชี)
-- ───────────────────────────────────────────
CREATE TABLE users (
  id            INTEGER PRIMARY KEY AUTOINCREMENT,
  name          TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  role          TEXT NOT NULL DEFAULT 'staff' CHECK (role IN ('staff')),
  password_hash TEXT NOT NULL            -- เก็บ hash เท่านั้น · ห้ามเก็บรหัสผ่านตรง ๆ
);

-- ───────────────────────────────────────────
-- categories — หมวดหมู่ประกาศ
-- ───────────────────────────────────────────
CREATE TABLE categories (
  id    INTEGER PRIMARY KEY,
  name  TEXT NOT NULL UNIQUE
);

-- ───────────────────────────────────────────
-- announcements — ประกาศข่าว
--   status      draft = ฉบับร่าง · published = เผยแพร่ · archived = เก็บเข้าคลัง
--   publish_at  วันเวลาเผยแพร่ (ISO 8601 พร้อมเขตเวลา เช่น 2026-10-08T09:00:00+07:00)
-- ───────────────────────────────────────────
CREATE TABLE announcements (
  id           TEXT PRIMARY KEY,
  title        TEXT NOT NULL,
  body         TEXT NOT NULL,
  category_id  INTEGER NOT NULL,
  status       TEXT NOT NULL DEFAULT 'draft'
               CHECK (status IN ('draft', 'published', 'archived')),
  publish_at   TEXT NOT NULL,
  author_name  TEXT NOT NULL,
  created_at   TEXT NOT NULL,

  FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE INDEX idx_announcements_status ON announcements(status, publish_at);

